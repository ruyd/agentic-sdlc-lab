// Deterministic drift check: everything that can be checked in code is checked here, so the
// nightly agent never has to explore the repo with shell commands. It only reads the report
// and files (or updates) one issue. If nothing drifted, the workflow skips the agent entirely.
//
//   npx tsx scripts/drift-facts.ts            # writes drift-report.md, prints the drift count
import { execFileSync } from "node:child_process";
import { appendFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { basename } from "node:path";

const DOCS = ["README.md", "CLAUDE.md", ...gitFiles().filter((f) => f.startsWith("docs/") && f.endsWith(".md"))];
const BUILTIN_SLASH_COMMANDS = new Set(["install-github-app", "init", "review", "help", "exit", "config", "permissions", "hooks", "agents", "mcp"]);

function gitFiles(): string[] {
  return execFileSync("git", ["ls-files"], { encoding: "utf8" }).split("\n").filter(Boolean);
}

function isIgnored(path: string): boolean {
  try {
    execFileSync("git", ["check-ignore", "-q", path]);
    return true;
  } catch {
    return false;
  }
}

const tracked = gitFiles();
const trackedBasenames = new Set(tracked.map((f) => basename(f)));
const trackedDirs = new Set(tracked.flatMap((f) => f.split("/").slice(0, -1).map((_, i, parts) => parts.slice(0, i + 1).join("/") + "/")));
const scripts: Record<string, string> = JSON.parse(readFileSync("package.json", "utf8")).scripts ?? {};

const drift: string[] = [];
const checked: string[] = [];

// 1. npm commands mentioned in docs must exist in package.json scripts.
for (const doc of DOCS) {
  const text = readFileSync(doc, "utf8");
  const names = new Set([...text.matchAll(/\bnpm run ([\w:-]+)/g)].map((m) => m[1]!));
  if (/\bnpm test\b/.test(text)) names.add("test");
  for (const name of names) {
    if (scripts[name]) checked.push(`npm script \`${name}\` (${doc})`);
    else drift.push(`${doc} mentions \`npm ${name === "test" ? "test" : "run " + name}\`, but package.json has no \`${name}\` script`);
  }
}

// 2. Slash commands mentioned in docs must exist in .claude/commands or .claude/skills.
for (const doc of DOCS) {
  const text = readFileSync(doc, "utf8");
  for (const m of text.matchAll(/`\/([a-z][a-z0-9-]*)[^`]*`/g)) {
    const name = m[1]!;
    if (BUILTIN_SLASH_COMMANDS.has(name)) continue;
    const found = tracked.includes(`.claude/commands/${name}.md`) || tracked.some((f) => f.startsWith(`.claude/skills/${name}/`));
    if (found) checked.push(`slash command \`/${name}\` (${doc})`);
    else drift.push(`${doc} mentions \`/${name}\`, but there is no tracked .claude/commands/${name}.md`);
  }
}

// 3. File and folder paths in backticks or Markdown links must exist (gitignored, generated paths are skipped).
for (const doc of DOCS) {
  const text = readFileSync(doc, "utf8");
  const docDir = doc.includes("/") ? doc.slice(0, doc.lastIndexOf("/") + 1) : "";
  const refs = new Set<string>();
  for (const m of text.matchAll(/`([A-Za-z0-9_.][A-Za-z0-9_.\/-]*)`/g)) {
    const token = m[1]!;
    if (token.includes("/") || /\.(md|ts|json|ya?ml|sh)$/.test(token)) refs.add(token);
  }
  for (const m of text.matchAll(/\]\(([^)#\s]+)\)/g)) {
    const link = m[1]!;
    if (!/^[a-z]+:/.test(link)) refs.add(new URL(link, `file:///${docDir}`).pathname.slice(1));
  }
  for (const ref of refs) {
    const exists = ref.endsWith("/")
      ? trackedDirs.has(ref)
      : ref.includes("/")
        ? tracked.includes(ref) || trackedDirs.has(ref + "/")
        : trackedBasenames.has(ref);
    if (exists) checked.push(`path \`${ref}\` (${doc})`);
    else if (isIgnored(ref)) checked.push(`path \`${ref}\` (${doc}) is generated and gitignored, skipped`);
    else drift.push(`${doc} references \`${ref}\`, which is not a tracked file or folder`);
  }
}

// 4. Dependencies a major version behind. `npm outdated` exits 1 when anything is outdated.
let outdated: Record<string, { current?: string; latest?: string }> = {};
try {
  outdated = JSON.parse(execFileSync("npm", ["outdated", "--json"], { encoding: "utf8" }) || "{}");
} catch (err) {
  outdated = JSON.parse((err as { stdout?: string }).stdout || "{}");
}
const major = (v?: string) => Number(v?.split(".")[0]);
for (const [pkg, info] of Object.entries(outdated)) {
  if (info.current && info.latest && major(info.latest) > major(info.current)) {
    drift.push(`dependency \`${pkg}\` is ${info.current}, latest major is ${info.latest}`);
  }
}
checked.push(`npm outdated: ${Object.keys(outdated).length} package(s) behind, majors flagged above`);

const report = [
  "# Drift report",
  "",
  `Generated by scripts/drift-facts.ts on ${new Date().toISOString().slice(0, 10)}.`,
  "",
  "## Drift found",
  ...(drift.length ? drift.map((d) => `- [ ] ${d}`) : ["None."]),
  "",
  "## Checked, no drift",
  ...[...new Set(checked)].map((c) => `- ${c}`),
  "",
].join("\n");

writeFileSync("drift-report.md", report);
if (process.env.GITHUB_OUTPUT) appendFileSync(process.env.GITHUB_OUTPUT, `drift_count=${drift.length}\n`);
console.log(`${drift.length} drift item(s); report in drift-report.md`);
if (existsSync("drift-report.md") && drift.length) console.log(drift.map((d) => `  - ${d}`).join("\n"));
